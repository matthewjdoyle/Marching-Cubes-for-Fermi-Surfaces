    INTEGER :: amb_face, edge, amb_int
    REAL(8), intent(in) :: cube(8)

    amb_int = 0

    select case(casen)

    case(4)

        amb_face = 1
        edge = interior_edge_test(amb_face, s, cube)
        amb_int = amb_int + interior_ambiguity_test(edge, cube)

        amb_face = 2
        edge = interior_edge_test(amb_face, s, cube)
        amb_int =  amb_int + interior_ambiguity_test(edge, cube)

