INTEGER FUNCTION face_test(face_number, cube)
! TESTS EACH FACE FOR INTERNAL AMBIGUITY AND THEN DECIDES IF
! THE NEGATIVE OR POSITIVE NODES SHOULD BE JOINED ALONG THE FACE
    integer, intent(in) :: face_number
    real(8), intent(in) :: cube(8)
    integer :: A, B, C, D
    ! A,B,C,D ARE TERMS IN EQN.2 IN PAPER

    select case(face_number)
    ! EACH FACE HAS DIFFERENT CORNER NODES
        case(-1,1)
            A = cube(1)
            B = cube(5)
            C = cube(6)
            D = cube(2)
        case(-2,2)
            A = cube(2)
            B = cube(6)
            C = cube(7)
            D = cube(3)
        case(-3,3)
            A = cube(3)
            B = cube(7)
            C = cube(8)
            D = cube(4)
        case(-4,4)
            A = cube(4)
            B = cube(8)
            C = cube(5)
            D = cube(1)
        case(-5,5)
            A = cube(1)
            B = cube(4)
            C = cube(3)
            D = cube(2)
        case(-6,6)
            A = cube(5)
            B = cube(8)
            C = cube(7)
            D = cube(6)
        case default
            write(6,*) "Invalid face code:", face_number
            write(6,'(F5.4)') cube
            A = 0
            B = 0
            C = 0
            D = 0
    end select

    IF (face_number * A * (A*C - B*D).gt.0) THEN
        face_test = 1
    ELSE
        face_test = 0
    END IF

END FUNCTION face_test

