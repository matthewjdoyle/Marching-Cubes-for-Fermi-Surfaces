INTEGER FUNCTION new_interior_test(cube, tunnelorientation)
! NEW TEST FOR CASE #13
! RETURNS 1 IF THE INTERIOR IS EMPTY AND TRIANGLES ARE ON FACES
! RETURNS 0 IF WE NEED TUNNEL THROUGH THE INTERIOR AND CALCULATES
! THE ORIENTATION FOR TRIANGLE TILING
    REAL(8), intent(in) :: cube(8)
    REAL(8) :: crit_point1, crit_point2
    REAL(8) :: a,b,c,d,e,f,g,h
    REAL(8) :: x1,y1,z1,x2,y2,z2
    REAL(8) :: dx,dy,dz,rom
    INTEGER :: ncrit
    INTEGER, intent(out) :: tunnelorientation

    a = -cube(1) + cube(2) + cube(4) - cube(3) + cube(5) - cube(6) - cube(8) + cube(7)
    b = cube(1) - cube(2) - cube(4) + cube(3)
    c = cube(1) - cube(2) - cube(5) + cube(6)
    d = cube(1) - cube(4) - cube(5) + cube(8)
    e = -cube(1) + cube(2)
    f = -cube(1) + cube(4)
    g = -cube(1) + cube(5)
    h = cube(1)

    ncrit = 0

    dx = b * c - a * e
    dy = b * d - a * f
    dz = c * d - a * g

    if ((dx.ne.0.0d+0).AND.(dy.ne.0.0d+0).AND.(dz.ne.0.0d+0)) then
        if (dx * dy * dz < 0) then
            new_interior_test = 1
        end if

        rom = sqrt(dx * dy * dz)

        x1 = (-d * dx - rom) / (a * dx)
        y1 = (-c * dy - rom) / (a * dy)
        z1 = (-b * dz - rom) / (a * dz)

        if ((x1 > 0).AND.(x1 < 1).AND.(y1 > 0).AND.(y1 < 1).AND.(z1 > 0).AND.(z1 < 1)) then
            ncrit = ncrit + 1
            crit_point1 = a*x1*y1*z1 + b*x1*y1 + c*x1*z1 + d*y1*z1 + e*x1 + f*y1 + g*z1 + h
        end if

        x2 = (-d * dx + rom) / (a * dx)
        y2 = (-c * dy + rom) / (a * dy)
        z2 = (-b * dz + rom) / (a * dz)

        if ((x2 > 0).AND.(x2 < 1).AND.(y2 > 0).AND.(y2 < 1).AND.(z2 > 0).AND.(z2 < 1)) then
            ncrit = ncrit + 1
            crit_point2 = a*x2*y2*z2 + b*x2*y2 + c*x2*z2 + d*y2*z2 + e*x2 + f*y2 + g*z2 + h
        end if

        if (ncrit < 2) then
            new_interior_test = 1
        else
            if (crit_point1 * crit_point2 > 0) then
                if (crit_point1 > 0) then
                    tunnelorientation = 1
                else
                    tunnelorientation = -1
                end if
                new_interior_test = 0
            end if
        end if
    else
        new_interior_test = 1
    end if

END FUNCTION new_interior_test



