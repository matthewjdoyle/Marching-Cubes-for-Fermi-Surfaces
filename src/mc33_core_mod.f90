FUNCTION interp(p1,p2,p1val,p2val)
    REAL(8) :: interp(3)
    real(8), intent(in) :: p1(3),p2(3),p1val,p2val
    real(8) :: mu

    if (ABS(p1val) < 0.00001) then
        interp(:) = p1(:)
    else if (ABS(p2val) < 0.00001) then
        interp(:) = p2(:)
    else if (ABS(p1val - p2val) < 0.00001) then
        interp(:) = p1(:)
    else
        mu = (- p1val) / (p2val - p1val)
        interp(1) = p1(1) + mu * (p2(1) - p1(1))
        interp(2) = p1(2) + mu * (p2(2) - p1(2))
        interp(3) = p1(3) + mu * (p2(3) - p1(3))
    end if
END FUNCTION

